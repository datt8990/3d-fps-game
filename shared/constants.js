export function getEffectiveWeaponStats(weaponId, weaponAttachments = {}, operatorId = 'vanguard') {
  const base = WEAPONS[weaponId] || WEAPONS.ak47;
  const op = OPERATORS[operatorId] || OPERATORS.vanguard;
  const optic = ATTACHMENTS.optic[weaponAttachments?.optic] || ATTACHMENTS.optic.iron;
  const muzzle = ATTACHMENTS.muzzle[weaponAttachments?.muzzle] || ATTACHMENTS.muzzle.none;
  const mag = ATTACHMENTS.mag[weaponAttachments?.mag] || ATTACHMENTS.mag.standard;

  const extraBullets = base.isMelee
    ? 0
    : (base.subClass === 'lmg'
      ? mag.extraBullets * 4
      : (base.isSniper || base.subClass === 'shotgun' ? Math.min(2, mag.extraBullets) : mag.extraBullets));

  return {
    ...base,
    magSize: base.magSize + extraBullets,
    recoilPitch: base.recoilPitch * muzzle.recoilMult,
    recoilYaw: base.recoilYaw * muzzle.recoilMult,
    spreadAds: base.spreadAds * (1 - (optic.adsBonus || 0)),
    adsFov: base.isSniper ? base.scopeFovs[0] : Math.max(22, (base.adsFov || 46) + (optic.zoomFovDelta || 0)),
    reloadTimeSec: base.isMelee ? 0 : Math.max(0.8, base.reloadTimeSec * mag.reloadMult * (1 - (op.reloadBonus || 0))),
    range: base.range * muzzle.rangeMult,
    suppressed: Boolean(base.builtInSuppressed || muzzle.suppressed),
    opticId: base.isSniper ? 'sniper_scope' : optic.id,
    muzzleId: base.builtInSuppressed ? 'suppressor' : muzzle.id,
    magId: mag.id
  };
}
